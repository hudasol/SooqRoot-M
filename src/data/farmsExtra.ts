/* ---------------- helpers ---------------- */

function line(
  productId: string,
  expectedHarvest: number,
  committed: number,
  reserve: number,
  unit: Unit,
  start: string,
  end: string,
  A: number,
  B: number,
  packaging: string[]
): FarmCapacityLine {
  return {
    productId,
    expectedHarvest,
    committed,
    reserve,
    unit,
    harvestWindowStart: start,
    harvestWindowEnd: end,
    gradeProbability: { A, B },
    packaging,
  };
}

/** Normalised canvas position from real coordinates, same frame as the original farms. */
function canvas(lat: number, lng: number): { x: number; y: number } {
  const x = Math.round(((lng - 53.6) / 2.9) * 100);
  const y = Math.round(((25.85 - lat) / 2.85) * 100);
  return { x: Math.max(4, Math.min(96, x)), y: Math.max(6, Math.min(94, y)) };
}

const CRATE = '5kg reusable crates';
const CARTON = '10kg cartons';

type NewFarm = Omit<Farm, 'x' | 'y' | 'contactName' | 'preferredLanguage' | 'areaAr'> & {
  areaAr: string;
  preferredLanguage?: Farm['preferredLanguage'];
};

function build(f: NewFarm): Farm {
  const { x, y } = canvas(f.lat, f.lng);
  return {
    ...f,
    x,
    y,
    contactName: 'Farm manager',
    preferredLanguage:
      f.preferredLanguage ??
      (f.foremanLanguage === 'ur' ? 'Urdu' : f.foremanLanguage === 'en' ? 'English' : 'Arabic'),
  };
}

